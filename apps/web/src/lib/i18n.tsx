function mergeTranslations(base: TranslationDictionary, override: TranslationDictionary): TranslationDictionary {
  const merged: TranslationDictionary = { ...base };
  for (const [key, value] of Object.entries(override)) {
    const baseValue = base[key];
    if (
      baseValue &&
      value &&
      typeof baseValue === "object" &&
      typeof value === "object" &&
      !Array.isArray(baseValue) &&
      !Array.isArray(value)
    ) {
      merged[key] = mergeTranslations(baseValue, value);
    } else {
      merged[key] = value;
    }
  }
  return merged;
}

function localizedTranslations(override: TranslationDictionary): TranslationDictionary {
  return mergeTranslations(englishTranslations, override);
}

